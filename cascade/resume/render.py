"""The generated blocks of the README and the write-up, rendered from artifacts/resume_stats.json.

Nothing here is typed by hand: every figure in a block comes from the stats file (itself built only
from run artifacts), and the arms' knowledge cutoffs and the task window come from the config files
that defined the experiment. A missing value is an error, never a blank or a default.

The README keeps its hand-written prose (architecture, reproduction, limitations) outside the
``<!-- results:begin -->`` / ``<!-- results:end -->`` markers; only the text between them is
replaced. The write-up is a template whose ``{{BLOCK}}`` tokens are filled the same way.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Any

from cascade.config import load_models, load_repos
from cascade.errors import CascadeError
from cascade.resume.stats import DEFAULT_PATH, load_stats

BEGIN = "<!-- results:begin -->"
END = "<!-- results:end -->"
README = Path("README.md")
WRITEUP_TEMPLATE = Path("docs/WRITEUP.template.md")
WRITEUP = Path("docs/WRITEUP.md")
GENERATED_NOTE = (
    "_Generated by `{script}` from `artifacts/resume_stats.json`. Do not edit by hand: rerun the "
    "script._"
)


class RenderError(CascadeError):
    """A block cannot be rendered from the inputs."""


# --- small formatters ---------------------------------------------------------------------------


def _iv(d: dict[str, Any] | None, f: Callable[[float], str]) -> str:
    if not d or d.get("point") is None:
        return "undefined"
    if d.get("lo") is None or d.get("hi") is None:
        return f(float(d["point"]))
    return f"{f(float(d['point']))} [{f(float(d['lo']))}, {f(float(d['hi']))}]"


def _pct(v: float) -> str:
    return f"{v:.1%}"


def _spct(v: float) -> str:
    return f"{v:+.1%}"


def _usd(v: float) -> str:
    return f"${v:,.4f}"


def _table(head: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def _banner(stats: dict[str, Any]) -> str:
    if stats.get("data_source") == "real":
        return ""
    return "> **SYNTHETIC DATA: nothing below is a result.**\n\n"


# --- blocks -------------------------------------------------------------------------------------


def provenance_block(stats: dict[str, Any]) -> str:
    f = stats["final"]
    return (
        f"- Data source: **{stats['data_source']}**; processing tier `{f['tier']}`.\n"
        f"- Final evaluation: commit `{f['commit'][:12]}`, matrix `{f['matrix_hash'][:16]}`, "
        f"{f['resamples']:,} paired-bootstrap resamples, seed {f['seed']}.\n"
        f"- Non-inferiority margin on resolve rate: {f['margin']} ({f['margin_basis']})."
    )


def counts_block(stats: dict[str, Any]) -> str:
    t, tok, spend = stats["tasks"], stats["tokens"], stats["spend_usd"]
    n_repos = t["repos"]["n"]
    repos = "unknown (some audited tasks were not evaluated)" if n_repos is None else str(n_repos)
    arms = ", ".join(f"`{a}`" for a in stats["arms"]["ids"].values())
    rows = [
        ["Repos", repos],
        ["Audited tasks (train / test)", f"{t['audited']['train']} / {t['audited']['test']}"],
        ["Evaluated tasks (train / test)", f"{t['evaluated']['train']} / {t['evaluated']['test']}"],
        ["Arms", f"{stats['arms']['n']}: {arms}"],
        ["Matrix attempts (all rows)", f"{stats['attempts']['n_matrix_rows']:,}"],
        ["Tokens (input + output + reasoning)", f"{tok['total']:,}"],
        ["Spend (experiments)", _usd(spend["experiment"])],
        ["Spend (live pilot)", _usd(spend["live_pilot"])],
        ["Spend (total ledger)", _usd(spend["total"])],
    ]
    return _table(["", ""], rows)


def policy_block(stats: dict[str, Any]) -> str:
    rows: list[list[str]] = []
    for name, p in stats["policies"].items():
        rows.append(
            [
                f"`{name}`",
                _iv(p["resolve_rate"], _pct),
                _iv(p["cost_per_task_usd"], _usd),
                _iv(p["cost_per_resolved_usd"], _usd),
                f"{p['mean_arms_tried']:.2f}",
            ]
        )
    n = next(iter(stats["policies"].values()))["n_tasks"]
    head = ["policy", "resolve rate (95% CI)", "cost per task", "cost per resolved", "arms tried"]
    return (
        f"Held-out test split, {n} tasks. Every policy is replayed from the same outcome matrix; "
        "cascade costs include every arm it tried.\n\n" + _table(head, rows)
    )


def headline_block(stats: dict[str, Any]) -> str:
    rows: list[list[str]] = []
    for name, c in stats["comparisons"].items():
        rows.append(
            [
                f"`{name}`",
                _iv(c["resolve_rate_diff"], _spct),
                _iv(c["cost_per_task_reduction"], _pct),
                _iv(c["oracle_savings_share"], _pct),
                c["verdict"],
            ]
        )
    head = [
        "vs `always_max`", "resolve-rate difference", "cost-per-task reduction",
        "share of oracle savings", "verdict",
    ]  # fmt: skip
    designated = stats["designated_policy"]
    margin = stats["final"]["margin"]
    if stats["claim_supported"]:
        verdict = (
            f"`{designated}` met the headline: its cost reduction interval excludes zero and the "
            f"lower end of its resolve-rate difference is inside the {margin} margin."
        )
    else:
        verdict = (
            "**No primary policy met the headline** (non-inferior within the margin AND a "
            "cost saving whose interval excludes zero), so the designated policy is "
            f"`{designated}`. This is the result, not a failure of the report."
        )
    return _table(head, rows) + f"\n\nMargin {margin}. {verdict}"


def verifier_block(stats: dict[str, Any]) -> str:
    rows = [
        [
            f"`{r['arm']}`", str(r["n"]), str(r["passed"]), str(r["claimed"]), str(r["false_pos"]),
            _iv(r["fp_rate"], _pct), _iv(r["fn_rate"], _pct),
        ]
        for r in stats["verifier"]["per_arm"]
    ]  # fmt: skip
    head = [
        "arm",
        "n",
        "passed hidden tests",
        "Verifier claimed",
        "false pos.",
        "FP rate",
        "FN rate",
    ]
    pooled = stats["verifier"]["pooled"]
    tail = (
        "No attempt failed, so a false-positive rate is undefined."
        if pooled is None
        else f"Pooled over arms: {pooled['false_positives']} of {pooled['n_failed_attempts']} "
        f"failing attempts were claimed successful ({_pct(pooled['fp_rate']['point'])}; "
        f"95% Wilson [{_pct(pooled['fp_rate']['lo'])}, {_pct(pooled['fp_rate']['hi'])}])."
    )
    return f"{stats['verifier']['scope']}.\n\n" + _table(head, rows) + "\n\n" + tail


def pilot_block(stats: dict[str, Any]) -> str:
    p = stats["pilot"]
    if p["n_reviewed"] == 0:
        return "No pilot draft has been reviewed."
    ci = p["accept_rate_ci"]
    merge = (
        "not recorded for any accepted draft"
        if p["merge_rate"] is None
        else f"{_pct(p['merge_rate'])} ({p['n_merged']}/{p['n_merge_known']} accepted drafts "
        "with a recorded outcome)"
    )
    median = "n/a" if p["median_lines_edited"] is None else f"{p['median_lines_edited']:g}"
    per = "n/a" if p["cost_per_accepted_usd"] is None else _usd(p["cost_per_accepted_usd"])
    return (
        f"{p['n_reviewed']} draft(s) on {p['n_repos']} owned or opt-in repo(s), each reviewed by a "
        f"human: {p['n_accepted_as_is']} accepted as-is, {p['n_minor_edits']} with minor edits, "
        f"{p['n_rejected']} rejected. Accept rate {_pct(p['accept_rate'])} "
        f"(95% Wilson [{_pct(ci[0])}, {_pct(ci[1])}]); merge rate {merge}; median lines edited "
        f"(accepted) {median}; cost per accepted draft {per} (all drafts' cost, rejected included)."
    )


def facts_block(stats: dict[str, Any], configs_dir: Path) -> str:
    models = load_models(configs_dir / "models.yaml")
    repos = load_repos(configs_dir / "repos.yaml")
    window = repos.date_window
    if isinstance(window.start, str) or isinstance(window.end, str):
        raise RenderError("repos.yaml date_window is not filled; cannot state the task window")
    by_arm = {a.arm_id: a for a in models.arms}
    cutoffs: list[str] = []
    for arm_id in stats["arms"]["ids"].values():
        arm = by_arm.get(arm_id)
        if arm is None:
            raise RenderError(f"arm {arm_id!r} is not defined in {configs_dir / 'models.yaml'}")
        cutoff = models.model_spec(arm.model).knowledge_cutoff
        cutoffs.append(f"`{arm_id}`: knowledge cutoff {cutoff}")
    noise = stats["noise"]
    noise_text = (
        "not available: the repeat-subset analysis (`cascade eval`, dev mode) has not been run on "
        "this matrix."
        if not noise
        else "; ".join(
            f"`{n['arm']}` flipped on {n['flips']} of {n['n_pairs']} repeated cells "
            f"({_iv(n['flip_rate'], _pct)})"
            for n in noise
        )
    )
    f = stats["final"]
    return (
        f"- Arms and knowledge cutoffs: {'; '.join(cutoffs)}.\n"
        f"- Task window: PRs merged {window.start} to {window.end}.\n"
        f"- Test split: {f['n_test_tasks']} tasks from {f['n_test_repos']} repo(s); every interval "
        "above is at that sample size.\n"
        f"- One run per matrix cell. Noise estimate (same cell, second seed, train subset): "
        f"{noise_text}"
    )


BLOCKS: dict[str, Callable[[dict[str, Any], Path], str]] = {
    "PROVENANCE": lambda s, _c: provenance_block(s),
    "COUNTS": lambda s, _c: counts_block(s),
    "POLICY_TABLE": lambda s, _c: policy_block(s),
    "HEADLINE": lambda s, _c: headline_block(s),
    "VERIFIER": lambda s, _c: verifier_block(s),
    "PILOT": lambda s, _c: pilot_block(s),
    "FACTS": facts_block,
}


def check_renderable(stats: dict[str, Any], *, allow_synthetic: bool) -> None:
    if stats.get("data_source") != "real" and not allow_synthetic:
        raise RenderError(
            f"the stats are from {stats.get('data_source')} data; real data only "
            "(--allow-synthetic is for tests)"
        )


def results_block(stats: dict[str, Any], configs_dir: Path, *, script: str) -> str:
    sections = [
        ("Provenance", "PROVENANCE"), ("Scale", "COUNTS"),
        ("Policies on the held-out test split", "POLICY_TABLE"),
        ("Headline: cost against always-max", "HEADLINE"),
        ("Verifier false positives", "VERIFIER"), ("Live pilot", "PILOT"),
        ("Facts the limitations refer to", "FACTS"),
    ]  # fmt: skip
    parts = [_banner(stats) + GENERATED_NOTE.format(script=script)]
    for title, key in sections:
        parts.append(f"### {title}\n\n{BLOCKS[key](stats, configs_dir)}")
    return "\n\n".join(parts)


def placeholder_block(script: str) -> str:
    return (
        GENERATED_NOTE.format(script=script)
        + "\n\n**No results yet.** The final evaluation has not been run. This section fills in "
        "from `artifacts/resume_stats.json` once it has."
    )


# --- README -------------------------------------------------------------------------------------


def replace_block(text: str, block: str) -> str:
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise RenderError(f"the README must contain exactly one {BEGIN} ... {END} pair")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{block}\n{END}{tail}"


def readme_main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="make_readme_results.py")
    ap.add_argument("--stats", type=Path, default=DEFAULT_PATH)
    ap.add_argument("--configs-dir", type=Path, default=Path("configs"))
    ap.add_argument("--readme", type=Path, default=README)
    ap.add_argument("--allow-synthetic", action="store_true", help="tests only")
    ap.add_argument("--check", action="store_true", help="fail if the README is out of date")
    ap.add_argument(
        "--placeholder", action="store_true", help="write the 'no results yet' block (no stats)"
    )
    args = ap.parse_args(argv)
    script = "scripts/make_readme_results.py"
    try:
        if args.placeholder:
            block = placeholder_block(script)
        else:
            stats = load_stats(args.stats)
            check_renderable(stats, allow_synthetic=args.allow_synthetic)
            block = results_block(stats, args.configs_dir, script=script)
        current = args.readme.read_text(encoding="utf-8")
        updated = replace_block(current, block)
    except (CascadeError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    if args.check:
        if updated != current:
            print(f"error: {args.readme} is out of date; run {script}", file=sys.stderr)
            return 1
        return 0
    args.readme.write_text(updated, encoding="utf-8")
    print(f"wrote the results block of {args.readme}")
    return 0


# --- write-up -----------------------------------------------------------------------------------

_TOKEN = re.compile(r"\{\{([A-Z_]+)\}\}")


def fill_template(template: str, stats: dict[str, Any], configs_dir: Path) -> str:
    unknown = sorted({t for t in _TOKEN.findall(template) if t not in BLOCKS})
    if unknown:
        raise RenderError(f"the write-up template has unknown block(s): {', '.join(unknown)}")
    return _TOKEN.sub(lambda m: BLOCKS[m.group(1)](stats, configs_dir), template)


def writeup_main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="make_writeup.py")
    ap.add_argument("--stats", type=Path, default=DEFAULT_PATH)
    ap.add_argument("--configs-dir", type=Path, default=Path("configs"))
    ap.add_argument("--template", type=Path, default=WRITEUP_TEMPLATE)
    ap.add_argument("--out", type=Path, default=WRITEUP)
    ap.add_argument("--allow-synthetic", action="store_true", help="tests only")
    ap.add_argument("--check", action="store_true", help="fail if the write-up is out of date")
    args = ap.parse_args(argv)
    try:
        stats = load_stats(args.stats)
        check_renderable(stats, allow_synthetic=args.allow_synthetic)
        body = fill_template(args.template.read_text(encoding="utf-8"), stats, args.configs_dir)
    except (CascadeError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    text = _banner(stats) + body
    if args.check:
        if not args.out.exists() or args.out.read_text(encoding="utf-8") != text:
            print(f"error: {args.out} is out of date; run scripts/make_writeup.py", file=sys.stderr)
            return 1
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0
